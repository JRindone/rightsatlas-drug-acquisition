function stageGroupFor(stage) {
  const value = stage.toLowerCase();
  if (value.includes("marketed +") || value.includes("portfolio") || value.includes("mixed")) return "Mixed / platform";
  if (value.includes("marketed") || value.includes("commercial") || value.includes("approved")) return "Commercial";
  if (value.includes("pre-approval") || value.includes("nda") || value.includes("registration") || value.includes("phase 3")) return "Phase 3 / registration";
  if (value.includes("phase 2")) return "Phase 2";
  if (value.includes("phase 1") || value.includes("clinical-stage")) return "Phase 1";
  return "Discovery / preclinical";
}

